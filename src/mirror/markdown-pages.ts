import * as fs from 'node:fs';
import * as path from 'node:path';
import * as crypto from 'node:crypto';
import { DatabaseSync } from 'node:sqlite';
import { Memory } from '../db/schema.js';

// Device names Windows refuses as file names regardless of extension (con.md, nul.md, ...)
const WINDOWS_RESERVED_NAMES = /^(?:con|prn|aux|nul|com[0-9]|lpt[0-9])(?:\..*)?$/i;

export function isWindowsReservedName(name: string): boolean {
  return WINDOWS_RESERVED_NAMES.test(name.trim());
}

/**
 * Converts an arbitrary module name into a safe file stem: `[a-z0-9_-]` only, any other
 * run of characters collapsed to `-`, falling back to `general` when nothing is left.
 */
export function slugifyModuleName(name: string): string {
  const slug = String(name ?? '')
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9_-]+/g, '-')
    .replace(/-{2,}/g, '-')
    .replace(/^[-_]+|[-_]+$/g, '')
    .slice(0, 80)
    .replace(/[-_]+$/g, '');
  if (!slug) return 'general';
  return isWindowsReservedName(slug) ? `${slug}-module` : slug;
}

/** Throws unless `target` resolves to a path strictly inside `dir`. */
export function assertInsideDir(dir: string, target: string): string {
  const resolvedDir = path.resolve(dir);
  const resolvedTarget = path.resolve(resolvedDir, target);
  const rel = path.relative(resolvedDir, resolvedTarget);
  if (!rel || rel === '..' || rel.startsWith(`..${path.sep}`) || path.isAbsolute(rel)) {
    throw new Error(`Refusing to write outside ${resolvedDir}: ${target}`);
  }
  return resolvedTarget;
}

/** File name for a module page; adds a short hash when slugging changed the name so distinct modules never collide. */
export function modulePageFileName(moduleName: string): string {
  const normModule = moduleName.trim().toLowerCase();
  const slug = slugifyModuleName(normModule);
  if (slug === normModule) return `${slug}.md`;
  const hash = crypto.createHash('sha256').update(normModule).digest('hex').slice(0, 6);
  return `${slug}-${hash}.md`;
}

export function renderModuleMarkdown(db: DatabaseSync, projectId: string, moduleName: string): string {
  const normModule = moduleName.trim().toLowerCase();

  // 1. Fetch active memories
  const activeRows = db.prepare(`
    SELECT m.*, GROUP_CONCAT(DISTINCT fl.file_path) as linked_files
    FROM memories m
    LEFT JOIN file_links fl ON fl.memory_id = m.id
    WHERE m.project_id = ?
      AND m.module = ?
      AND m.valid_to IS NULL
      AND m.status != 'superseded'
      AND m.status != 'dormant'
    GROUP BY m.id
    ORDER BY m.pinned DESC, (m.kind = 'error_trap') DESC, m.reward_score DESC, m.created_at DESC
  `).all(projectId, normModule) as any[];

  // 2. Fetch superseded/historical memories
  const supersededRows = db.prepare(`
    SELECT m.*, GROUP_CONCAT(DISTINCT fl.file_path) as linked_files
    FROM memories m
    LEFT JOIN file_links fl ON fl.memory_id = m.id
    WHERE m.project_id = ?
      AND m.module = ?
      AND (m.valid_to IS NOT NULL OR m.status = 'superseded')
    GROUP BY m.id
    ORDER BY COALESCE(m.valid_to, m.created_at) DESC
  `).all(projectId, normModule) as any[];

  const lines: string[] = [
    `# Module: ${normModule}`,
    '',
    '> Auto-generated by FastrMemory. Active rules are at the top; superseded history is preserved below for Git diffs.',
    '',
    '---',
    '',
    '## Compiled Truth (Active Rules & Traps)',
    ''
  ];

  if (activeRows.length === 0) {
    lines.push('_No active memories recorded for this module._', '');
  } else {
    for (const mem of activeRows) {
      const kindBadge = mem.kind === 'error_trap' ? 'TRAP' : mem.kind.toUpperCase();
      const filesBadge = mem.linked_files ? `\`${mem.linked_files.split(',').join('`, `')}\`` : 'None';
      const statusBadge = mem.status === 'verified' ? 'verified' : 'staging';

      lines.push(`### [${mem.id}] [${kindBadge}] ${mem.title}`);
      lines.push(`- **Kind**: \`${mem.kind}\``);
      lines.push(`- **Status**: \`${statusBadge}\` (Reward Score: ${mem.reward_score})`);
      lines.push(`- **Linked Files**: ${filesBadge}`);
      lines.push(`- **Active Since**: \`${mem.valid_from}\``);
      lines.push('');
      lines.push(mem.content);
      lines.push('', '---', '');
    }
  }

  lines.push('## Append-Only Timeline (History & Superseded)', '');

  if (supersededRows.length === 0) {
    lines.push('_No superseded history for this module._', '');
  } else {
    for (const mem of supersededRows) {
      const expiredRange = `[EXPIRED ${mem.valid_from} -> ${mem.valid_to || 'N/A'}]`;
      const supersededBy = mem.superseded_by_id ? `\`[${mem.superseded_by_id}]\`` : 'Manual Retirement';
      const reasonText = mem.superseded_reason ? `- **Reason**: ${mem.superseded_reason}` : '';

      lines.push(`### ${expiredRange} [${mem.id}] ${mem.title}`);
      lines.push(`- **Superseded By**: ${supersededBy}`);
      if (reasonText) lines.push(reasonText);
      lines.push(`- **Historical Status**: \`${mem.status}\``);
      lines.push('');
      lines.push('> ' + mem.content.split('\n').join('\n> '));
      lines.push('', '---', '');
    }
  }

  return lines.join('\n');
}

export function syncModulePage(
  db: DatabaseSync,
  projectRoot: string,
  projectId: string,
  moduleName: string
): string {
  const normModule = moduleName.trim().toLowerCase();
  const pagesDir = path.join(projectRoot, '.fastr', 'pages');
  if (!fs.existsSync(pagesDir)) {
    fs.mkdirSync(pagesDir, { recursive: true });
  }

  const content = renderModuleMarkdown(db, projectId, normModule);
  const targetFile = assertInsideDir(pagesDir, modulePageFileName(normModule));
  fs.writeFileSync(targetFile, content, 'utf-8');
  return targetFile;
}

export function syncAllModulePages(
  db: DatabaseSync,
  projectRoot: string,
  projectId: string
): string[] {
  const rows = db.prepare(`
    SELECT DISTINCT module FROM memories WHERE project_id = ?
  `).all(projectId) as { module: string }[];

  const syncedFiles: string[] = [];
  for (const row of rows) {
    if (row.module) {
      const filePath = syncModulePage(db, projectRoot, projectId, row.module);
      syncedFiles.push(filePath);
    }
  }

  return syncedFiles;
}
